"""C-V5 parity of this corpus's own display list against the expected SVG documents of oracles-svg (R-H, label placement LP/1).

    python -B -I tools/parity_svg.py

For every row G, N, X, Y of oracles-svg that renders without options, the node centres, the path numbers and the label positions of the expected SVG document
are compared with the integers of the display list built by tools/dlist.py (which applies LP/1 through the reference of oracles-lp).  Not part of the
generator: oracles-svg is regenerated by another author, so this is run last, against whatever state that corpus is in.  Exit status 0 = parity holds,
1 = a document disagrees, 2 = not run (a file of oracles-svg does not match its own SHA256SUMS: the corpus is mid-regeneration).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import scenes  # noqa: E402
import selfcheck  # noqa: E402


def main():
    scenes.build_all()
    try:
        res = selfcheck._parity()
    except RuntimeError as e:
        print("NOT RUN: %s (oracles-svg is mid-regeneration or inconsistent)" % e)
        return 2
    except AssertionError as e:
        print("PARITY FAILS: %s" % e)
        return 1
    for name, ok, _d in res:
        print(("ok: " if ok else "FAIL: ") + name)
    return 0 if all(r[1] for r in res) else 1


if __name__ == "__main__":
    sys.exit(main())
