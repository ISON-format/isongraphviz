// packages/layout-core/test/oracles.test.ts - the IGL/1 oracle corpus (fixtures/oracles-igl): FROZEN 2026-11-16 after two independent audits (see fixtures/oracles-igl/README.md).
// Expected layout bytes were produced by Python only (tools/make_oracles.py); nothing here regenerates them.
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { verifyScene } from "isongraph-visualize-scene-core";
import { describe, expect, it } from "vitest";
import { bindLayout } from "../src/bind.js";
import { verifyReproducible } from "../src/compute.js";
import { computeFixedLayout } from "../src/fixed.js";
import { computeForceLayout } from "../src/force.js";
import { verifyLayout } from "../src/verify.js";
import { ORACLES_IGL, layoutError, read } from "./helpers.js";
import { ACCEPT, REJECT, enc } from "./verify-cases.js";

interface Row { id: string; group: string; scene: string; input: string; expected: string; error: string }
const rows: Row[] = readFileSync(join(ORACLES_IGL, "EXPECT.tsv"), "utf8").replace(/\n$/, "").split("\n").slice(1) /* not trim(): the last row may end in an empty, tab-terminated field */.map((l) => {
  const [id, group, scene, input, expected, error] = l.split("\t") as string[];
  return { id: id!, group: group!, scene: scene!, input: input!, expected: expected!, error: error! };
});
const by = (g: string) => rows.filter((r) => r.group === g);
const at = (rel: string) => join(ORACLES_IGL, rel);
const sha = (b: Uint8Array | Buffer) => createHash("sha256").update(b).digest("hex");
const same = (a: Uint8Array, b: Uint8Array) => Buffer.from(a).equals(Buffer.from(b));
const verdict = (got: string) => (got === "no error" ? "" : got);

function walk(dir: string, out: string[] = []): string[] {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) { if (f !== "tools") walk(p, out); } else if (f !== "SHA256SUMS") out.push(relative(ORACLES_IGL, p).replace(/\\/g, "/"));
  }
  return out;
}

describe("the IGL oracle corpus (frozen)", () => {
  it("the manifest has 92 rows (F 13, X 5, V 46, S 20, B 8)", () => {
    expect(rows).toHaveLength(92);
    expect(Object.fromEntries(["force", "fixed", "verify", "scene", "bind"].map((g) => [g, by(g).length]))).toEqual({ force: 13, fixed: 5, verify: 46, scene: 20, bind: 8 });
    expect(new Set(rows.map((r) => r.id)).size).toBe(92);
  });

  it("SHA256SUMS lists exactly the committed files (no stray, no missing) and every digest matches", () => {
    const sums = readFileSync(at("SHA256SUMS"), "utf8").trim().split("\n").map((l) => { const m = /^([0-9a-f]{64}) [ *](.+)$/.exec(l); if (!m) throw new Error("bad line " + l); return [m[1]!, m[2]!.replace(/^\.\//, "")] as const; });
    expect(sums.map((s) => s[1]).sort()).toEqual(walk(ORACLES_IGL).sort());
    for (const [hash, file] of sums) expect(sha(readFileSync(at(file))), file).toBe(hash);
  });

  it("every .layout.sha256 file is the digest of its layout file", () => {
    for (const f of walk(ORACLES_IGL).filter((x) => x.endsWith(".layout.sha256"))) {
      expect(readFileSync(at(f), "utf8").trim(), f).toBe(sha(readFileSync(at(f.replace(".layout.sha256", ".layout.json")))));
    }
  });

  it("force rows: the TypeScript producer reproduces the Python-generated bytes and digests exactly, and the artifacts verify, bind and are reproducible", async () => {
    for (const r of by("force")) {
      const scene = read(at(r.scene));
      const out = await computeForceLayout(scene, JSON.parse(r.input));
      expect(same(out.layoutBytes, read(at(r.expected))), `${r.id} bytes`).toBe(true);
      expect(out.layoutSha256, `${r.id} digest`).toBe(readFileSync(at(r.expected.replace(".layout.json", ".layout.sha256")), "utf8").trim());
      await expect(bindLayout(scene, read(at(r.expected))), `${r.id} bind`).resolves.toBeDefined();
      await expect(verifyReproducible(scene, read(at(r.expected))), `${r.id} reproducible`).resolves.toBe("reproduced");
    }
  });

  it("fixed rows: reproduced from the supplied positions, bound, and reported not-recomputable", async () => {
    for (const r of by("fixed")) {
      const scene = read(at(r.scene));
      const out = await computeFixedLayout(scene, JSON.parse(readFileSync(at(r.input), "utf8")));
      expect(same(out.layoutBytes, read(at(r.expected))), r.id).toBe(true);
      await expect(bindLayout(scene, read(at(r.expected))), r.id).resolves.toBeDefined();
      await expect(verifyReproducible(scene, read(at(r.expected))), r.id).resolves.toBe("not-recomputable");
    }
  });

  it("verify rows: each file gives exactly its expected verdict (four verify: V21, V24 and the coordinate-range boundaries V45, V46; forty-two are rejected)", async () => {
    let accepted = 0;
    for (const r of by("verify")) {
      const got = verdict(await layoutError(() => verifyLayout(read(at(r.input)))));
      if (!r.error) accepted++;
      expect(got, r.id).toBe(r.error);
    }
    expect(accepted).toBe(4);
  });

  it("the Python-written V files are BYTE-IDENTICAL to the TypeScript mutation table (two independent mutation implementations)", () => {
    const table = new Map<string, Uint8Array>();
    for (const [name, input] of REJECT) table.set(name.slice(0, 3), typeof input === "string" ? enc(input) : input);
    for (const [name, input] of ACCEPT) table.set(name.slice(0, 3), enc(input));
    expect(table.size).toBe(46);
    for (const r of by("verify")) expect(same(table.get(r.id)!, read(at(r.input))), `${r.id} differs between the TS table and the Python file`).toBe(true);
  });

  it("scene rows: every hand-written scene is accepted by verifyScene; refusals have the expected reason; controls reproduce the Python bytes", async () => {
    for (const r of by("scene")) {
      const bytes = read(at(r.scene));
      await expect(verifyScene(bytes), `${r.id} verifyScene`).resolves.toBeDefined();
      if (r.error) expect(verdict(await layoutError(() => computeForceLayout(bytes, JSON.parse(r.input)))), r.id).toBe(r.error);
      else expect(same((await computeForceLayout(bytes, JSON.parse(r.input))).layoutBytes, read(at(r.expected))), r.id).toBe(true);
    }
  });

  it("bind rows (B01 is the forged-hash case: same nodes, different edges)", async () => {
    for (const r of by("bind")) {
      if (r.error.startsWith("IGS:")) {
        await expect(bindLayout(read(at(r.scene)), read(at(r.expected))), r.id).rejects.toMatchObject({ name: "IgsError", reason: r.error.split("/")[1] });
        continue;
      }
      expect(verdict(await layoutError(() => bindLayout(read(at(r.scene)), read(at(r.expected))))), r.id).toBe(r.error);
    }
  });
});
